"""Multi-provider management, priority routing, health checking, and benchmarking."""

import logging
import time
from typing import Any, Dict, List, Optional, Tuple

from ..config import config
from ..jd_analysis.models import JobDescription, RequirementMatrix
from ..profile.models import MasterProfile, ProjectItem
from .providers import PROVIDER_REGISTRY, BaseAIProvider
from .structured_schemas import TailoredResumeContent

logger = logging.getLogger("resume_builder.ai.manager")


class ProviderManager:
    """Manages provider lifecycle, health checks, benchmarking, and cascading fallback."""

    def __init__(self):
        self._providers: Dict[str, BaseAIProvider] = {}
        for name, cls in PROVIDER_REGISTRY.items():
            p_cfg = config.get_provider_config(name)
            self._providers[name] = cls(config_dict=p_cfg)

    def get_provider(self, name: str) -> Optional[BaseAIProvider]:
        return self._providers.get(name.lower())

    def get_priority_chain(self, requested_provider: Optional[str] = None) -> List[BaseAIProvider]:
        """
        Builds the fallback sequence.
        If a specific provider is requested by the user, it is placed at the front.
        """
        chain: List[BaseAIProvider] = []
        seen = set()

        if requested_provider:
            req_lower = requested_provider.lower().strip()
            if req_lower in self._providers:
                chain.append(self._providers[req_lower])
                seen.add(req_lower)
            else:
                logger.warning(f"Requested provider '{requested_provider}' not recognized. Using default priority.")

        for name in config.provider_priority:
            name_lower = name.lower().strip()
            if name_lower in self._providers and name_lower not in seen:
                provider = self._providers[name_lower]
                if provider.enabled:
                    chain.append(provider)
                    seen.add(name_lower)

        # Always ensure offline is available as final fallback
        if "offline" not in seen and "offline" in self._providers:
            chain.append(self._providers["offline"])

        return chain

    def check_all_providers(self) -> Dict[str, Any]:
        """
        Runs health checks across all registered providers.
        Returns detailed report dictionary.
        """
        results = []
        for name in config.provider_priority:
            if name in self._providers:
                p = self._providers[name]
                health = p.check_health()
                health["priority_rank"] = len(results) + 1
                health["is_enabled"] = p.enabled
                results.append(health)

        # Determine primary usable provider
        primary = None
        for r in results:
            if r["is_enabled"] and r["configured"] and r["auth_status"] in ("Valid", "Not Required"):
                primary = r["provider"]
                break

        return {
            "providers": results,
            "selected_primary": primary or "Offline Python Engine",
            "fallback_sequence": [r["provider"] for r in results if r["is_enabled"]],
        }

    def generate(
        self,
        profile: MasterProfile,
        selected_projects: List[ProjectItem],
        jd: JobDescription,
        req_matrix: RequirementMatrix,
        requested_provider: Optional[str] = None,
        offline: bool = False,
    ) -> Tuple[TailoredResumeContent, str, str]:
        """
        Execute generation with multi-provider fallback.
        Returns: (TailoredResumeContent, provider_name, model_name)
        """
        if offline:
            logger.info("Explicit offline mode requested. Using Offline Python Engine.")
            offline_p = self._providers["offline"]
            content, model_str = offline_p.generate_tailored_content(
                profile, selected_projects, jd, req_matrix
            )
            return content, offline_p.display_name, model_str

        chain = self.get_priority_chain(requested_provider)
        last_error = None

        for provider in chain:
            if not provider.is_configured():
                logger.info(f"Skipping {provider.display_name} (credentials not configured).")
                continue

            logger.info(f"Attempting resume generation with provider: {provider.display_name}")
            try:
                content, model_str = provider.generate_tailored_content(
                    profile, selected_projects, jd, req_matrix
                )
                logger.info(
                    f"✓ Content successfully generated by [{provider.display_name}] using model [{model_str}]"
                )
                return content, provider.display_name, model_str

            except PermissionError as pe:
                logger.warning(
                    f"Authentication failure on {provider.display_name}: {pe}. "
                    "Disabling provider for this run and trying next in sequence."
                )
                last_error = pe
            except Exception as e:
                err_str = str(e)
                logger.warning(f"Provider {provider.display_name} failed: {err_str[:120]}. Falling back...")
                last_error = e

        # Final safety net: offline provider
        logger.warning(f"All online providers failed. Triggering offline fallback engine. Last error: {last_error}")
        offline_p = self._providers["offline"]
        content, model_str = offline_p.generate_tailored_content(
            profile, selected_projects, jd, req_matrix
        )
        return content, offline_p.display_name, model_str

    def benchmark_providers(
        self,
        profile: MasterProfile,
        projects: List[ProjectItem],
    ) -> List[Dict[str, Any]]:
        """
        Run a privacy-safe, lightweight benchmark across configured providers.
        Uses a small sample test JD and stripped profile.
        """
        test_jd = JobDescription(
            raw_text="Looking for a Software Engineer with Java, Spring Boot, SQL, and React experience.",
            company_name="Benchmark Labs",
            job_title="Software Engineer",
            required_skills=["Java", "Spring Boot", "SQL", "React 18"],
        )
        req_matrix = RequirementMatrix()

        results = []
        for name, provider in self._providers.items():
            if not provider.is_configured():
                results.append({
                    "provider": provider.display_name,
                    "status": "Skipped (Not Configured)",
                    "latency_sec": None,
                    "schema_valid": None,
                    "bearing_fault_pos2": None,
                    "model_used": "N/A",
                })
                continue

            t0 = time.time()
            try:
                content, model_name = provider.generate_tailored_content(
                    profile, projects[:4], test_jd, req_matrix
                )
                latency = round(time.time() - t0, 2)
                p2_valid = (
                    len(content.tailored_projects) >= 2
                    and "bearing" in content.tailored_projects[1].title.lower()
                )
                results.append({
                    "provider": provider.display_name,
                    "status": "Success",
                    "latency_sec": latency,
                    "schema_valid": True,
                    "bearing_fault_pos2": p2_valid,
                    "model_used": model_name,
                })
            except Exception as e:
                latency = round(time.time() - t0, 2)
                results.append({
                    "provider": provider.display_name,
                    "status": f"Failed: {str(e)[:60]}",
                    "latency_sec": latency,
                    "schema_valid": False,
                    "bearing_fault_pos2": False,
                    "model_used": "Error",
                })

        return results
